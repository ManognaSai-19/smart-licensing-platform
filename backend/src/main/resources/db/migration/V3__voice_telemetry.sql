-- ===================================================================
-- SMART DIGITAL LICENSING PLATFORM - FLYWAY VOICE TELEMETRY (V3)
-- Voice interaction logging for research evaluation & usability metrics
-- ===================================================================

CREATE TABLE voice_interaction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT REFERENCES applications(id) ON DELETE SET NULL,
    service_code VARCHAR(100) NOT NULL,
    field_key VARCHAR(100) NOT NULL,
    language VARCHAR(20) NOT NULL,
    raw_transcript TEXT,
    normalized_value TEXT,
    confidence_score DOUBLE PRECISION,
    duration_ms INTEGER,
    correction_count INTEGER NOT NULL DEFAULT 0,
    confirmed_by_user BOOLEAN NOT NULL DEFAULT TRUE,
    input_mode VARCHAR(50) NOT NULL DEFAULT 'VOICE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_voice_logs_service ON voice_interaction_logs(service_code);
CREATE INDEX idx_voice_logs_field ON voice_interaction_logs(field_key);
CREATE INDEX idx_voice_logs_created_at ON voice_interaction_logs(created_at);
