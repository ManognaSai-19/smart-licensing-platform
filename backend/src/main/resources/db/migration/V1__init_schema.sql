-- ===================================================================
-- SMART DIGITAL LICENSING PLATFORM - FLYWAY INITIAL SCHEMA (V1)
-- ===================================================================

-- 1. Users & Authentication
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL CHECK (role IN ('CITIZEN', 'OFFICER', 'ADMIN')),
    phone_number VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_role ON users(role);

-- 2. Departments
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Officer Department Assignments
CREATE TABLE officer_department_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_officer_department UNIQUE (user_id, department_id)
);

-- 4. Services
CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    department_id BIGINT NOT NULL REFERENCES departments(id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sample_fee NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    processing_time_days INT NOT NULL DEFAULT 7,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_services_code ON services(code);
CREATE INDEX idx_services_department ON services(department_id);

-- 5. Service Dynamic Form Fields
CREATE TABLE service_fields (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    field_key VARCHAR(100) NOT NULL,
    label_en VARCHAR(255) NOT NULL,
    label_te VARCHAR(255) NOT NULL,
    data_type VARCHAR(50) NOT NULL CHECK (data_type IN ('TEXT', 'NUMBER', 'DATE', 'SELECT')),
    is_required BOOLEAN NOT NULL DEFAULT TRUE,
    validation_rules TEXT,
    options_json TEXT,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_service_field UNIQUE (service_id, field_key)
);

CREATE INDEX idx_service_fields_service ON service_fields(service_id, display_order);

-- 6. Required Document Types per Service
CREATE TABLE required_document_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    document_code VARCHAR(100) NOT NULL,
    name_en VARCHAR(255) NOT NULL,
    name_te VARCHAR(255) NOT NULL,
    is_required BOOLEAN NOT NULL DEFAULT TRUE,
    accepted_mime_types VARCHAR(255) NOT NULL DEFAULT 'image/jpeg,image/png,application/pdf',
    max_size_bytes BIGINT NOT NULL DEFAULT 5242880,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_service_doc_code UNIQUE (service_id, document_code)
);

CREATE INDEX idx_req_docs_service ON required_document_types(service_id);

-- 7. Applications
CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number VARCHAR(100) NOT NULL UNIQUE,
    citizen_id BIGINT NOT NULL REFERENCES users(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'UNDER_VERIFICATION', 'APPROVED', 'REJECTED', 'RESUBMITTED')),
    form_data TEXT,
    language_preference VARCHAR(10) NOT NULL DEFAULT 'en',
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_applications_citizen ON applications(citizen_id);
CREATE INDEX idx_applications_status ON applications(status);
CREATE INDEX idx_applications_service ON applications(service_id);
CREATE INDEX idx_applications_ref ON applications(reference_number);

-- 8. Application Uploaded Documents (Private Storage Keys)
CREATE TABLE application_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    document_type_id BIGINT NOT NULL REFERENCES required_document_types(id),
    file_name VARCHAR(255) NOT NULL,
    storage_key VARCHAR(255) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    file_checksum VARCHAR(128),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_app_docs_application ON application_documents(application_id);

-- 9. OCR Extraction Metadata & Raw Text
CREATE TABLE ocr_extractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES application_documents(id) ON DELETE CASCADE,
    engine_name VARCHAR(100) NOT NULL,
    engine_version VARCHAR(50) NOT NULL,
    raw_text TEXT,
    extracted_fields TEXT,
    confidence_score NUMERIC(5, 4),
    processing_status VARCHAR(50) NOT NULL DEFAULT 'COMPLETED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ocr_extractions_document ON ocr_extractions(document_id);

-- 10. Explainable Pre-Screening Findings
CREATE TABLE prescreening_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    document_id BIGINT REFERENCES application_documents(id) ON DELETE SET NULL,
    rule_code VARCHAR(100) NOT NULL,
    field_key VARCHAR(100),
    outcome VARCHAR(50) NOT NULL CHECK (outcome IN ('PASS', 'FAIL', 'WARNING', 'NEEDS_MANUAL_REVIEW')),
    expected_value TEXT,
    extracted_value TEXT,
    explanation TEXT NOT NULL,
    suggested_action TEXT,
    confidence NUMERIC(5, 4),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_findings_application ON prescreening_findings(application_id);

-- 11. Human Officer Review Decisions
CREATE TABLE review_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    officer_id BIGINT NOT NULL REFERENCES users(id),
    decision VARCHAR(50) NOT NULL CHECK (decision IN ('APPROVED', 'REJECTED')),
    rejection_reason TEXT,
    internal_notes TEXT,
    decided_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_decisions_application ON review_decisions(application_id);
CREATE INDEX idx_decisions_officer ON review_decisions(officer_id);

-- 12. Application Status Audit History
CREATE TABLE application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    from_status VARCHAR(50),
    to_status VARCHAR(50) NOT NULL,
    changed_by_user_id BIGINT NOT NULL REFERENCES users(id),
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_history_application ON application_status_history(application_id);

-- 13. Persistent Notifications Feed
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    application_id BIGINT REFERENCES applications(id) ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_recipient_read ON notifications(recipient_id, is_read);

-- 14. Audit Logs (Non-sensitive Security Trail)
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(100) NOT NULL,
    resource_id VARCHAR(100),
    ip_address VARCHAR(50),
    details TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_logs_actor_created ON audit_logs(actor_id, created_at);
